#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""场馆映射（CBA 2026-2027）。

官方门户接口只在临近比赛/完赛后返回 stadium 字段，因此这里维护一份人工核定的兜底映射：
- 单主场球队：直连主场馆
- 多主场球队：按日期 / 主场序号切换场馆
官方 stadium 一旦有值，优先使用官方值。
"""

# 单主场：teamId -> (场馆, 城市)
SINGLE_HOME = {
    29125: ("上海体育馆", "上海"),
    29128: ("黄龙体育中心体育馆", "杭州"),          # 浙江浙商证券（广厦）
    29129: ("辽宁体育馆", "沈阳"),
    29130: ("山东高速篮球馆", "济南"),
    29132: ("山西体育中心汾酒体育馆", "太原"),
    29133: ("江宁体育中心体育馆", "南京"),          # 南京同曦宙光
    29134: ("晋江祖昌体育馆", "晋江"),
    29136: ("国家奥林匹克体育中心体育馆", "北京"),   # 北京控股
    29137: ("长春市体育馆", "长春"),                # 长白山恩都里（吉林）
    29138: ("东丽体育馆", "天津"),
    29140: ("义乌梅湖体育中心体育馆", "义乌"),
    100074683: ("宁波市体育发展中心体育馆", "宁波"),
    29127: ("成都市温江区体育馆", "成都"),
}


def home_venue(team_id: int, date: str, home_index: int):
    """返回 (场馆, 城市)。home_index 为该队本赛季第几个主场（从 1 开始）。"""
    if team_id in SINGLE_HOME:
        return SINGLE_HOME[team_id]

    # 深圳马可波罗：一、二阶段龙华文体中心，三阶段起移师深圳市体育中心
    if team_id == 29131:
        return (("深圳市体育中心体育馆", "深圳") if date >= "2027-03-10"
                else ("龙华文体中心综合馆", "深圳"))
    # 北京首钢：一、二阶段首钢园冰球馆，三阶段首都体育馆
    if team_id == 29115:
        return (("首都体育馆", "北京") if date >= "2027-03-10"
                else ("首钢园冰球馆", "北京"))
    # 江苏肯帝亚：12-27 之前丹阳，之后南通
    if team_id == 29118:
        return (("南通体育会展中心体育馆", "南通") if date >= "2026-12-27"
                else ("丹阳市体育馆", "丹阳"))
    # 青岛崂山啤酒：01-11 至 01-18 在平度，其余国信钻石馆
    if team_id == 29135:
        return (("平度奥体中心体育馆", "青岛平度")
                if "2027-01-11" <= date <= "2027-01-18"
                else ("国信体育中心钻石体育馆", "青岛"))
    # 广州智都集团：01-09 至 01-24 在花都东风体育馆
    if team_id == 29139:
        return (("花都东风体育馆", "广州")
                if "2027-01-09" <= date <= "2027-01-24"
                else ("天河体育馆", "广州"))
    # 广东东阳光：顺德 2 场（12-14、03-11）、茂名 1 场（01-06），其余东莞篮球中心
    if team_id == 29124:
        if date in ("2026-12-14", "2027-03-11"):
            return ("顺德德胜体育中心体育馆", "佛山顺德")
        if date == "2027-01-06":
            return ("茂名奥体中心体育馆", "茂名")
        return ("东莞银行篮球中心", "东莞")
    # 新疆广汇能源：赛季前 4 个主场在自治区体育中心，之后乌鲁木齐奥体中心
    if team_id == 29117:
        return (("新疆维吾尔自治区体育中心体育馆", "乌鲁木齐") if home_index <= 4
                else ("乌鲁木齐奥体中心体育馆", "乌鲁木齐"))
    return ("主场馆待定", "待定")


# 俱乐部杯小组赛：按赛区（groupName 前缀 A/B/C/D 组）
CLUB_CUP_GROUPS = {
    "A": ("烟台八角湾国际体育中心体育馆", "烟台"),
    "B": ("洪山体育馆", "武汉"),
    "C": ("银川赛区体育馆（场馆待定）", "银川"),
    "D": ("琼海赛区体育馆（场馆待定）", "琼海"),
}
CLUB_CUP_FINALS = ("南宁（决赛阶段，场馆待定）", "南宁")

# 季前赛赛区（groupName 如“高县站”）
PRESEASON_STATIONS = {
    "高县站": ("高县赛区体育馆（场馆待定）", "四川宜宾高县"),
}


def cup_venue(group_name: str, date: str):
    """俱乐部杯场馆：小组赛按赛区，淘汰赛/决赛按南宁。"""
    if group_name:
        key = group_name[0].upper()
        if key in CLUB_CUP_GROUPS:
            return CLUB_CUP_GROUPS[key]
    if date >= "2027-02-01":
        return CLUB_CUP_FINALS
    return CLUB_CUP_GROUPS["B"]        # 上海久事在 B 组（武汉赛区）


def preseason_venue(group_name: str):
    return PRESEASON_STATIONS.get(group_name or "", ("赛区场馆待定", group_name or "待定"))
